// A single HTML file keeps the firmware's HTTP routing and runtime tiny.
import { build, transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'src/web');
const [template, css, script] = await Promise.all([
  readFile(path.join(directory, 'index.html'), 'utf8'),
  readFile(path.join(directory, 'style.css'), 'utf8').then(input => transform(input, {
    loader: 'css', minify: true, target: 'es2020', legalComments: 'none',
  })),
  build({ entryPoints: [path.join(directory, 'app.js')], bundle: true,
    write: false, format: 'iife', minify: true, target: 'es2020',
    legalComments: 'none', charset: 'utf8' }),
]);
const html = '<!-- Generated by pnpm build. Edit src/web sources instead. -->\n'
  + template.replace(/>\s+</g, '><').trim().replace('<!-- WEB_STYLE -->', () => `<style>${css.code.trim()}</style>`)
    .replace('<!-- WEB_SCRIPT -->', () => `<script>${script.outputFiles[0].text.trim()}</script>`)
    + '\n';
const destination = path.join(directory, 'embedded.html');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== html) throw Error('Embedded UI is stale. Run pnpm build.');
} else {
  await writeFile(destination, html);
}
console.log(`Embedded UI: ${Buffer.byteLength(html)} bytes${process.argv.includes('--check') ? ' (current)' : ''}`);
